const DICTS: Record<Locale, Dict> = { en, es, pt };

// ---- Runtime --------------------------------------------------------------------------------------------------
const currentLocale = (): Locale => {
  if (typeof document === 'undefined') return 'en';
  const l = (document.documentElement.lang || 'en').toLowerCase();
  return l.startsWith('es') ? 'es' : l.startsWith('pt') ? 'pt' : 'en';
};

/** Translate outside React (e.g. text saved into a new tab). Uses the current <html lang>. */
export function translate(key: string, vars?: Record<string, string | number>, locale: Locale = currentLocale()): string {
  let s = DICTS[locale][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

const listeners = new Set<() => void>();
let observer: MutationObserver | null = null;
function subscribe(cb: () => void) {
  listeners.add(cb);
  if (!observer && typeof MutationObserver !== 'undefined' && typeof document !== 'undefined') {
    observer = new MutationObserver(() => listeners.forEach((l) => l()));
    observer.observe(document.documentElement, { attributes: true, attributeFilter: ['lang'] });
  }
  return () => {
    listeners.delete(cb);
  };
}

/** Returns t(key, vars) for the current language; components re-render when the language changes. */
export function useT() {
  const locale = useSyncExternalStore(subscribe, currentLocale, () => 'en' as Locale);
  return (key: string, vars?: Record<string, string | number>) => translate(key, vars, locale);
}

/** The current language code, reactive. */
export function useLocale(): Locale {
  return useSyncExternalStore(subscribe, currentLocale, () => 'en' as Locale);
}
